#ifndef LEXER_H
#define LEXER_H

#include <stddef.h>

// ============================================================================
// File: lexer.h
// Purpose: Lexical analyzer (tokenizer) and pre-validator for math expressions.
// Role:
//   Validates input strings for balanced parentheses and permitted character
//   sets, then scans raw characters into structured tokens (TokenList) with
//   1-based column position tracking for precise error diagnostics.
// ============================================================================

// Categorization tags for scanned tokens
typedef enum {
    TK_NUMBER, // Numeric literals (integer, fractional, scientific notation: "123", "45.67", "1e-5")
    TK_IDENT,  // Identifiers for functions and variables ("sin", "cos", "x", "ans", "pi", "e")
    TK_OP,     // Arithmetic operators ("+", "-", "*", "/", "%", "^", "!")
    TK_LPAREN, // Opening parenthesis "("
    TK_RPAREN, // Closing parenthesis ")"
    TK_COMMA,  // Argument list separator ","
    TK_END     // Sentinel indicating end-of-input
} TokenType;

// Representation of an individual lexical token
typedef struct {
    TokenType type; // Token category tag
    char     *text; // Dynamically allocated string containing the token lexeme
    size_t    pos;  // 1-indexed source column position for error caret reporting
} Token;

// Dynamic array of tokens generated by the lexer
typedef struct {
    Token  *items;    // Array of Token structures
    size_t  count;    // Number of active tokens in the list
    size_t  capacity; // Total allocated slots in items buffer
} TokenList;

// Error codes emitted by pre-validation and lexing
typedef enum {
    ERR_OK = 0,          // No error encountered
    ERR_INVALID_CHAR,    // Forbidden or non-mathematical character encountered
    ERR_UNBALANCED_PAREN,// Mismatched '(' or ')' parenthesis depth
    ERR_INVALID_NUMBER,  // Malformed numeric literal (e.g. multiple decimal points)
    ERR_EMPTY_EXPR       // Input string contains only whitespace or is empty
} ErrorCode;

// Structure describing a parsing or lexing error with diagnostic information
typedef struct {
    int    code;         // Error classification (matches ErrorCode enum)
    size_t position;     // 1-based source column where error occurred
    char   message[256]; // Human-readable error description
} ParseError;

// ----------------------------------------------------------------------------
// Pre-validation & Token List Lifecycle
// ----------------------------------------------------------------------------

// Pre-scans the raw expression string to ensure balanced parentheses and valid characters
// Sets *err_pos to the column of failure if invalid; returns 1 if valid, 0 if invalid
int validate_expression(const char *input, size_t *err_pos);

// Initializes an empty TokenList
void token_list_init(TokenList *tl);

// Frees all tokens, their duplicate text buffers, and the items array in a TokenList
void token_list_free(TokenList *tl);

// Appends a new token with duplicated lexeme text and column position to the TokenList
int token_list_add(TokenList *tl, TokenType type, const char *text, size_t pos);

// ----------------------------------------------------------------------------
// Lexer Entry Point
// ----------------------------------------------------------------------------

// Converts raw input string into a list of tokens, populating err if a syntax error occurs
// Returns 1 on success, 0 on failure
int lex_tokenize(const char *input, TokenList *out, ParseError *err);

// Helper to convert a TokenType enum into a human-readable string (e.g., "NUMBER", "IDENT")
const char *token_type_name(TokenType type);

#endif /* LEXER_H */


